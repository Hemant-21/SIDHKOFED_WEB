export const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { en, hi };

export type TranslationParams = Record<string, string | number>;

/** Replace `{name}` placeholders in a translated string with `params[name]`. */
function interpolate(value: string, params?: TranslationParams): string {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

/**
 * Translate a UI key for a language, optionally interpolating `{name}` placeholders
 * from `params`. Falls back to the other language if the current one is missing or
 * left blank (a deliberately empty string is treated the same as "not translated
 * yet" - content editors can stub a key with `''` and fill it in later without
 * breaking the page). If neither language has a non-empty value, returns `''`
 * rather than leaking the raw key into the UI - callers that need to hide an empty
 * section should check for a falsy result.
 */
export function translate(lang: Language, key: TranslationKey, params?: TranslationParams): string {
  const value = DICTIONARIES[lang][key];
  const resolved = value || DICTIONARIES[lang === 'en' ? 'hi' : 'en'][key] || '';
  return interpolate(resolved, params);
}
